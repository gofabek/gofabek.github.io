function localize(lang) {
  const s = T[lang];
  const tr = (key, fallback) => (s[key] !== undefined ? s[key] : fallback);
  let html = index;

  html = html
    .replace(/<html lang="uz">/, `<html lang="${lang}">`)
    .replace(/(<(\w+)\b[^>]*\sdata-i18n="(\w+)"[^>]*>)([^<]*)(<\/\2>)/g, (m, open, tag, key, text, close) => open + esc(tr(key, text)) + close)
    .replace(/(<(\w+)\b[^>]*\sdata-i18n-html="(\w+)"[^>]*>)([\s\S]*?)(<\/\2>)/g, (m, open, tag, key, inner, close) => open + tr(key, inner) + close)
    .replace(/(data-i18n-placeholder="(\w+)"[^>]*?\splaceholder=")[^"]*"/g, (m, pre, key) => `${pre}${esc(tr(key, ''))}"`)
    .replace(/(data-i18n-aria="(\w+)"[^>]*?\saria-label=")[^"]*"/g, (m, pre, key) => `${pre}${esc(tr(key, ''))}"`)
    .replace(/class="lang-btn active"/, 'class="lang-btn"')
    .replace(new RegExp(`class="lang-btn" data-lang="${lang}"`), `class="lang-btn active" data-lang="${lang}"`);

  // <head>: titles, descriptions, canonical, locale
  html = html
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(s.meta_title)}</title>`)
    .replace(/(<meta name="description" content=")[^"]*"/, `$1${esc(s.meta_desc)}"`)
    .replace(/(<meta property="og:title" content=")[^"]*"/, `$1${esc(s.meta_title)}"`)
    .replace(/(<meta property="og:description" content=")[^"]*"/, `$1${esc(s.meta_desc)}"`)
    .replace(/(<meta property="og:locale" content=")[^"]*"/, `$1${LOCALES[lang]}"`)
    .replace(/(<link rel="canonical" href=")[^"]*"/, `$1${SITE}/${lang}/"`)
    .replace(/(<meta property="og:url" content=")[^"]*"/, `$1${SITE}/${lang}/"`)
    .replace(/(<meta property="og:image" content=")[^"]*"/, `$1${SITE}/${ogImage('home', lang)}"`)
    .replace(/(<meta property="og:image:alt" content=")[^"]*"/, `$1${esc(s.meta_title)}"`);

  // Relative URLs now live one folder deeper.
  html = html
    .replace(new RegExp(`\\b(src|href)="(?!https?:|#|mailto:|data:|/|\\.\\./|(?:${[...Object.keys(PROJECTS).map(slug), 'cv'].join('|')})/)([^"]+)"`, 'g'), '$1="../$2"')
    .replace(/srcset="([^"]+)"/g, (m, list) => `srcset="${list.replace(/(^|,\s*)(?!https?:|\/)/g, '$1../')}"`);

  return html.replace('<body>', `<body>\n    ${GENERATED}`);
}

